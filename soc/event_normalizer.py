"""Security Event Ingestion, Normalization, Deduplication, and Correlation Engine."""

import hashlib
from datetime import datetime, timezone
from typing import Any, Dict, Optional, Tuple
import uuid

from soc.models import IncidentSeverity, NormalizedSecurityEvent


class EventNormalizer:
    """Normalizes heterogeneous security findings into uniform NormalizedSecurityEvent records."""

    @staticmethod
    def normalize_guardduty(raw_event: Dict[str, Any]) -> NormalizedSecurityEvent:
        """Normalizes an Amazon GuardDuty finding event."""
        detail = raw_event.get("detail", raw_event)
        finding_type = detail.get("type", "GuardDutyFinding")
        title = detail.get("title", finding_type)
        gd_severity_val = float(detail.get("severity", 4.0))

        # GuardDuty severity scale: 0.1-3.9 Low, 4.0-6.9 Medium, 7.0-8.9 High, 9.0-10.0 Critical
        if gd_severity_val >= 9.0:
            severity = IncidentSeverity.CRITICAL
        elif gd_severity_val >= 7.0:
            severity = IncidentSeverity.HIGH
        elif gd_severity_val >= 4.0:
            severity = IncidentSeverity.MEDIUM
        else:
            severity = IncidentSeverity.LOW

        resource = detail.get("resource", {})
        res_type = resource.get("resourceType", "AWS::Resource")
        res_id = resource.get("resourceId") or resource.get("instanceDetails", {}).get("instanceId") or "unknown-resource"
        actor = detail.get("service", {}).get("action", {}).get("awsApiCallAction", {}).get("remoteIpDetails", {}).get("ipAddressV4")

        fingerprint = hashlib.sha256(f"GuardDuty:{finding_type}:{res_id}".encode("utf-8")).hexdigest()[:16]

        return NormalizedSecurityEvent(
            event_id=raw_event.get("id", f"EVT-{uuid.uuid4().hex[:8]}"),
            source="GuardDuty",
            event_type=finding_type,
            severity=severity,
            resource_id=res_id,
            resource_type=res_type,
            actor=actor,
            fingerprint=fingerprint,
            details=detail,
        )

    @staticmethod
    def normalize_security_hub(raw_event: Dict[str, Any]) -> NormalizedSecurityEvent:
        """Normalizes an AWS Security Hub finding event."""
        finding = raw_event.get("detail", {}).get("findings", [raw_event])[0] if "findings" in raw_event.get("detail", {}) else raw_event
        title = finding.get("Title", finding.get("title", "SecurityHubFinding"))
        finding_type = finding.get("Types", ["GeneralSecurityFinding"])[0] if isinstance(finding.get("Types"), list) else "GeneralSecurityFinding"

        sev_label = finding.get("Severity", {}).get("Label") or finding.get("severity", "MEDIUM")
        sev_map = {
            "CRITICAL": IncidentSeverity.CRITICAL,
            "HIGH": IncidentSeverity.HIGH,
            "MEDIUM": IncidentSeverity.MEDIUM,
            "LOW": IncidentSeverity.LOW,
            "INFORMATIONAL": IncidentSeverity.INFORMATIONAL,
        }
        severity = sev_map.get(str(sev_label).upper(), IncidentSeverity.MEDIUM)

        resources = finding.get("Resources", [{}])
        primary_res = resources[0] if resources else {}
        res_id = primary_res.get("Id", "unknown-resource")
        res_type = primary_res.get("Type", "AWS::Resource")

        fingerprint = hashlib.sha256(f"SecurityHub:{title}:{res_id}".encode("utf-8")).hexdigest()[:16]

        return NormalizedSecurityEvent(
            event_id=finding.get("Id", f"EVT-{uuid.uuid4().hex[:8]}"),
            source="SecurityHub",
            event_type=title,
            severity=severity,
            resource_id=res_id,
            resource_type=res_type,
            fingerprint=fingerprint,
            details=finding,
        )

    @staticmethod
    def normalize_fraud_alert(raw_alert: Dict[str, Any]) -> NormalizedSecurityEvent:
        """Normalizes a high-risk fraud alert generated by FinGuard AI Phase 7 scoring."""
        case_id = raw_alert.get("case_id") or raw_alert.get("transaction_id", "unknown-txn")
        risk_score = float(raw_alert.get("risk_score", 0.85))
        severity = IncidentSeverity.CRITICAL if risk_score >= 0.85 else IncidentSeverity.HIGH

        fingerprint = hashlib.sha256(f"FinGuardFraud:{raw_alert.get('account_id', 'ACC')}:{raw_alert.get('channel', 'UPI')}".encode("utf-8")).hexdigest()[:16]

        return NormalizedSecurityEvent(
            event_id=raw_alert.get("alert_id", f"EVT-FRAUD-{uuid.uuid4().hex[:8]}"),
            source="FinGuardFraud",
            event_type="HighVelocityFraudBurst",
            severity=severity,
            resource_id=raw_alert.get("account_id", case_id),
            resource_type="BankAccount",
            actor=raw_alert.get("customer_id"),
            fingerprint=fingerprint,
            details=raw_alert,
        )

    @classmethod
    def normalize(cls, raw: Dict[str, Any]) -> NormalizedSecurityEvent:
        """Dispatcher that automatically detects source schema and returns NormalizedSecurityEvent."""
        source = str(raw.get("source") or raw.get("detail-type", ""))
        detail = raw.get("detail", {})
        raw_id = str(raw.get("id", ""))
        
        if (
            "guardduty" in source.lower()
            or "GuardDuty" in raw
            or raw_id.startswith("gd-")
            or ":" in str(detail.get("type", ""))
        ):
            return cls.normalize_guardduty(raw)
        elif "securityhub" in source.lower() or "Resources" in raw or "FindingProviderFields" in raw or "Title" in raw:
            return cls.normalize_security_hub(raw)
        elif "fraud" in source.lower() or "risk_score" in raw:
            return cls.normalize_fraud_alert(raw)
        else:
            # Fallback generic normalization
            res_id = raw.get("resource_id", "arn:aws:::generic-resource")
            evt_type = raw.get("event_type", "GenericSecurityAlert")
            fp = hashlib.sha256(f"Generic:{evt_type}:{res_id}".encode("utf-8")).hexdigest()[:16]
            return NormalizedSecurityEvent(
                event_id=raw.get("id") or raw.get("event_id", f"EVT-{uuid.uuid4().hex[:8]}"),
                source=raw.get("source", "InternalSecurity"),
                event_type=evt_type,
                severity=IncidentSeverity(raw.get("severity", "MEDIUM").upper()),
                resource_id=res_id,
                resource_type=raw.get("resource_type", "AWS::Resource"),
                fingerprint=fp,
                details=raw,
            )

